import { AiConversationAuditLog } from '../../domain/models/ai-conversation-audit-log.entity';
import { ConversationId } from '../../domain/value-objects/conversation-id.vo';
import { AuditHistoryCursor } from '../../domain/value-objects/audit-history-cursor.vo';

export const AI_CONVERSATION_AUDIT_REPOSITORY_PORT = Symbol('IAiConversationAuditRepositoryPort');

/**
 * Keyset-based pagination request for audit log history.
 *
 * **Audit Lifecycle Notice:**
 * Ordered deterministically by `(createdAt DESC, id DESC)`.
 * Audit access operates independently of conversation lifecycle (i.e. even if a conversation
 * is purged, its audit logs remain intact and fully paginatable).
 */
export interface AuditPaginationRequest {
  readonly cursor?: AuditHistoryCursor | string | null;
  readonly limit?: number; // Defaults to 20, max 100
  readonly inspectorUserId?: string;
  readonly conversationId?: ConversationId | string;
}

/**
 * Typed result of a paginated audit log query.
 */
export interface AuditPaginationResult {
  readonly items: readonly AiConversationAuditLog[];
  readonly nextCursor: AuditHistoryCursor | null;
  readonly hasMore: boolean;
}

/**
 * Outbound port for persistent storage and retrieval of clinical and supervisory conversation audit logs.
 *
 * **Independent Audit Retention:**
 * Audit records are immutable and do NOT rely on relational cascade deletion from conversations.
 * They persist independently across the entire regulatory compliance retention window.
 *
 * **Transaction Compatibility:**
 * Audit log recording can participate in existing application transactions or execute in an isolated
 * transaction so that access audits are recorded even if the inspected operation aborts.
 */
export interface IAiConversationAuditRepositoryPort {
  /**
   * Persists an immutable conversation audit log.
   */
  save(auditLog: AiConversationAuditLog): Promise<AiConversationAuditLog>;

  /**
   * Lists audit logs for a specific conversation within a tenant.
   */
  listByConversation(
    tenantId: string,
    conversationId: ConversationId | string,
    limit?: number,
  ): Promise<AiConversationAuditLog[]>;

  /**
   * Lists audit logs generated by a specific clinical inspector or supervisory user within a tenant.
   */
  listByInspector(
    tenantId: string,
    inspectorUserId: string,
    limit?: number,
  ): Promise<AiConversationAuditLog[]>;

  /**
   * Lists audit logs using deterministic keyset pagination.
   */
  listPaginated?(
    tenantId: string,
    request?: AuditPaginationRequest,
  ): Promise<AuditPaginationResult>;
}
